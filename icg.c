/* Intermediate code generation: three-address code for an assignment like x=a+b*(c-d).
   Two stacks (shunting-yard):
     operand stack  : names and temporaries t1, t2 ...
     operator stack : + - * / (
   Before an operator is pushed, every operator of stronger or equal priority on the
   operator stack is turned into one line of code. */
#include <stdio.h>
#include <ctype.h>
#include <string.h>
#include <stdlib.h>

char op_stack[100];               /* operators */
int op_top = -1;
char val_stack[100][12];          /* operands */
int val_top = -1;
int tcount = 1;                   /* next temporary number */

/* priority of an operator; '(' is lowest so it is never generated by mistake */
int prec(char c) {
    if (c == '*' || c == '/') return 2;
    if (c == '+' || c == '-') return 1;
    return 0;
}

void fail(const char *why) {
    printf("Invalid expression: %s\n", why);
    exit(1);
}

/* take one operator and two operands, print one 3AC line, push the temporary */
void generate(void) {
    char op, a[12], b[12], t[12];
    if (op_top < 0 || val_top < 1 || op_stack[op_top] == '(') {
        fail("operator or operand missing");
    }
    op = op_stack[op_top--];
    strcpy(b, val_stack[val_top--]);              /* right operand is on top */
    strcpy(a, val_stack[val_top--]);
    sprintf(t, "t%d", tcount++);
    printf("%s = %s %c %s\n", t, a, op, b);
    strcpy(val_stack[++val_top], t);
}

int main(void) {
    char line[100], result[12], tok[12], c;
    int p = 0, q = 0, k, expect_operand = 1;

    printf("Enter an assignment (e.g. x=a+b*c): ");
    if (scanf("%99s", line) != 1) {
        fputs("No input\n", stderr);
        return 1;
    }
    /* name on the left of = */
    while (line[p] && line[p] != '=' && q < 11) {
        result[q++] = line[p++];
    }
    result[q] = '\0';
    if (line[p] != '=' || q == 0) {
        fail("expected  name=expression");
    }
    p++;

    for (; line[p]; p++) {
        c = line[p];
        if (isalnum((unsigned char)c) || c == '_') { /* operand: read the whole name or number */
            if (!expect_operand) fail("two operands in a row");
            k = 0;
            while (isalnum((unsigned char)line[p]) || line[p] == '_') {
                if (k >= 11) fail("name too long");
                tok[k++] = line[p++];
            }
            tok[k] = '\0';
            p--;
            strcpy(val_stack[++val_top], tok);
            expect_operand = 0;
        } else if (c == '(') {                        /* open bracket: just push */
            if (!expect_operand) fail("operator missing before (");
            op_stack[++op_top] = c;
        } else if (c == ')') {                        /* close bracket: finish everything inside */
            if (expect_operand) fail("operand missing before )");
            while (op_top >= 0 && op_stack[op_top] != '(') generate();
            if (op_top < 0) fail("unbalanced )");
            op_top--;                                 /* throw the '(' away */
        } else if (c == '+' || c == '-' || c == '*' || c == '/') {
            if (expect_operand) fail("operand missing before operator");
            while (op_top >= 0 && prec(op_stack[op_top]) >= prec(c)) {
                generate();                           /* top operator is stronger or equal */
            }
            op_stack[++op_top] = c;
            expect_operand = 1;
        } else {
            fail("unknown character");
        }
    }
    if (expect_operand) fail("expression ends early");
    while (op_top >= 0) {                             /* flush the remaining operators */
        if (op_stack[op_top] == '(') fail("unbalanced (");
        generate();
    }
    printf("%s = %s\n", result, val_stack[val_top]);  /* final assignment */
    return 0;
}
